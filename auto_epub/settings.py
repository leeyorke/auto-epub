def migrate_legacy_dir(legacy_name: str, target: Path) -> None:
    """把工作目录里的旧版缓存/日志目录整体搬到 ~/.auto-epub 下

    只在「旧目录存在且目标目录还不存在」时做一次整目录搬移：目标已存在
    说明新版已经跑过，旧目录按遗留物处理，留在原处不自动删除。搬移失败
    也不阻塞翻译——最坏情况只是丢一次断点续传。
    """
    legacy = Path.cwd() / legacy_name
    if not legacy.is_dir() or target.exists():
        return
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(legacy), str(target))
    except OSError:
        pass


